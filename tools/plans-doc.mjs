#!/usr/bin/env node
// Generates docs/PLANS.md, the list of every plan quota-board knows, from plans/*.json.
// Usage: node tools/plans-doc.mjs           write docs/PLANS.md
//        node tools/plans-doc.mjs --check   exit 1 if docs/PLANS.md is out of date (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { APP_ROOT } from '../src/meta.mjs';
import { loadAll } from '../src/plans.mjs';

const OUT = join(APP_ROOT, 'docs', 'PLANS.md');
const PERIOD = { '5h': '5-hour', day: 'daily', week: 'weekly', month: 'monthly' };
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const money = p => `$${p.amount % 1 ? p.amount.toFixed(2) : p.amount}/${p.period === 'year' ? 'yr' : 'mo'}${p.currency && p.currency !== 'USD' ? ` (${p.currency})` : ''}`;

const { plans, errors } = loadAll();
if (errors.length) { console.error(`Fix plan errors first (node tools/check.mjs):\n  ${errors.join('\n  ')}`); process.exit(1); }

const byVendor = new Map();
for (const p of [...plans].sort((a, b) => a.vendor.localeCompare(b.vendor) || a.price.amount - b.price.amount || a.name.localeCompare(b.name))) {
  if (!byVendor.has(p.vendor)) byVendor.set(p.vendor, []);
  byVendor.get(p.vendor).push(p);
}
const live = plans.filter(p => p.detect).length;

const lines = [
  '# Supported plans',
  '',
  '<!-- Generated by `node tools/plans-doc.mjs` from plans/*.json. Edit the plan files, not this page. -->',
  '',
  `quota-board knows ${plans.length} plans from ${byVendor.size} providers. ${live} of them have live usage read from a local login; the rest take readings you enter with \`quota-board set\` or on the dashboard.`,
  '',
  'Prices are list prices in USD unless noted. Record what you actually pay with `quota-board price <plan-id> <amount>`.',
  '',
  'Something wrong or missing? Run `quota-board report`, or see [CONTRIBUTING.md](../CONTRIBUTING.md).',
  ''
];
for (const [vendor, ps] of byVendor) {
  lines.push(`## ${vendor}`, '', '| Plan | Id | Price | Limits | Live usage | Last checked |', '|---|---|---|---|---|---|');
  for (const p of ps) {
    const limits = p.meters.length ? p.meters.map(m => { const per = PERIOD[m.period] || m.period; return m.label.toLowerCase().includes(per.replace('-hour', '')) ? m.label : `${m.label} (${per})`; }).join('; ') : 'No fixed limits';
    const name = `[${cell(p.name)}](../plans/${p.id}.json)${p.status !== 'active' ? ` *${p.status}*` : ''}`;
    lines.push(`| ${name} | \`${p.id}\` | ${money(p.price)} | ${cell(limits)} | ${p.detect ? p.detect.collector : 'manual'} | ${p.lastVerified} |`);
  }
  lines.push('');
}
const md = lines.join('\n');

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== md) { console.error('docs/PLANS.md is out of date. Run: node tools/plans-doc.mjs'); process.exit(1); }
  console.log('ok    docs/PLANS.md is up to date');
} else {
  mkdirSync(join(APP_ROOT, 'docs'), { recursive: true });
  writeFileSync(OUT, md);
  console.log(`wrote docs/PLANS.md (${plans.length} plans)`);
}
