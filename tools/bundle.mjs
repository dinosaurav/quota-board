#!/usr/bin/env node
// Builds dist/quota-board.mjs: the whole app (code, plan files, dashboard) in one file that runs without installing:
//   curl -fsSL https://raw.githubusercontent.com/dinosaurav/quota-board/main/dist/quota-board.mjs | node --input-type=module -
// The file unpacks itself once per version into ~/.quota-board/cache/<hash>/ and runs bin/quota-board.mjs from there.
// The output is pure ASCII so Windows PowerShell 5.1 can pipe it to node without mangling characters.
// Usage: node tools/bundle.mjs           write dist/quota-board.mjs
//        node tools/bundle.mjs --check   exit 1 if dist/quota-board.mjs is out of date
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { APP_ROOT, VERSION } from '../src/meta.mjs';

const INCLUDE = ['package.json', 'LICENSE', 'bin', 'src', 'collectors', 'plans', 'web'];
const OUT = join(APP_ROOT, 'dist', 'quota-board.mjs');

function walk(p, out) {
  const abs = join(APP_ROOT, p);
  if (statSync(abs).isDirectory()) for (const n of readdirSync(abs).sort()) walk(join(p, n), out);
  else out[relative(APP_ROOT, abs).split('\\').join('/')] = readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
  return out;
}
const files = {};
for (const p of INCLUDE) walk(p, files);

const ascii = s => s.replace(/[\u007f-\uffff]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const payload = ascii(JSON.stringify(files));
const hash = createHash('sha256').update(payload).digest('hex').slice(0, 12);

// No #! line: PowerShell may prepend a byte-order mark when piping, and a #! line can't follow one.
const bundle = `// quota-board ${VERSION} (${hash}), single-file edition. Generated by tools/bundle.mjs; don't edit.
// Run without installing:
//   curl -fsSL https://raw.githubusercontent.com/dinosaurav/quota-board/main/dist/quota-board.mjs | node --input-type=module -
//   irm https://raw.githubusercontent.com/dinosaurav/quota-board/main/dist/quota-board.mjs | node --input-type=module -
// Add arguments after the dash, e.g. "node --input-type=module - -v".
// It unpacks its files once into ~/.quota-board/cache/${hash}/, removes older copies, and runs from there.
import { mkdirSync, writeFileSync, existsSync, readdirSync, renameSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { pathToFileURL } from 'node:url';

process.removeAllListeners('warning');
const [major, minor] = process.versions.node.split('.').map(Number);
if (major < 22 || (major === 22 && minor < 5)) { console.error('quota-board needs Node.js 22.5 or newer (you have ' + process.version + '). Get it at https://nodejs.org'); process.exit(1); }

const HASH = '${hash}';
const FILES = ${payload};

const cache = join(process.env.QUOTA_BOARD_HOME || join(homedir(), '.quota-board'), 'cache');
const dir = join(cache, HASH);
if (!existsSync(join(dir, '.complete'))) {
  const tmp = dir + '.tmp-' + process.pid;
  for (const [path, text] of Object.entries(FILES)) {
    const file = join(tmp, path);
    mkdirSync(dirname(file), { recursive: true, mode: 0o700 });
    writeFileSync(file, text);
  }
  writeFileSync(join(tmp, '.complete'), HASH);
  rmSync(dir, { recursive: true, force: true });
  try { renameSync(tmp, dir); } catch (e) { if (!existsSync(join(dir, '.complete'))) throw e; rmSync(tmp, { recursive: true, force: true }); }
  for (const n of readdirSync(cache)) if (n !== HASH && /^[0-9a-f]{12}(\\.tmp-\\d+)?$/.test(n)) rmSync(join(cache, n), { recursive: true, force: true });
}
await import(pathToFileURL(join(dir, 'bin', 'quota-board.mjs')).href);
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== bundle) { console.error('dist/quota-board.mjs is out of date. Run: node tools/bundle.mjs'); process.exit(1); }
  console.log('ok    dist/quota-board.mjs is up to date');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, bundle);
  console.log(`wrote dist/quota-board.mjs (${Math.round(bundle.length / 1024)} KB, ${Object.keys(files).length} files, ${hash})`);
}
